// ── 투어 문구 색인: 앵커 키 → [{ page, title, desc, term }] ─────────────────────
const TOUR_KEY_RE = /^\[data-tour="([^"]+)"\]$/;
let tourIndex = null;
function getTourIndex() {
  if (tourIndex) return tourIndex;
  tourIndex = new Map();
  Object.entries(TOURS).forEach(([page, steps]) => {
    (steps || []).forEach((s) => {
      const m = s.el && TOUR_KEY_RE.exec(s.el);
      if (!m) return;
      if (!tourIndex.has(m[1])) tourIndex.set(m[1], []);
      tourIndex.get(m[1]).push({ page, title: s.title, desc: s.desc, term: s.term || null });
    });
  });
  return tourIndex;
}

/** 투어에 적힌 그 앵커의 설명 — 지금 화면의 투어를 우선, 없으면 다른 화면 투어의 것. */
export function tourTextFor(key, page) {
  const list = getTourIndex().get(key);
  if (!list || !list.length) return null;
  const hit = list.find((x) => x.page === page) || list[0];
  return { title: hit.title, desc: hit.desc, term: hit.term };
}

const pageName = (id) => {
  const m = PAGE_META[id];
  if (!m) return '';
  return `${m.icon ? m.icon + ' ' : ''}${m.label}`;
};

/**
 * 앵커 키 하나의 호버 설명. 없으면 null(→ 호출 쪽이 바깥 앵커로 올라가 다시 찾는다).
 * @returns {{title:string, desc:string, term:string|null}|null}
 */
export function resolveHelp(key, page) {
  if (!key) return null;
  if (key === 'page-title') {
    const what = PAGE_HELP[page]?.what;
    return what ? { title: pageName(page), desc: what, term: null } : null;
  }
  if (key.startsWith('nav-')) {
    const target = key.slice(4);
    const what = PAGE_HELP[target]?.what;
    if (what) return { title: pageName(target), desc: what, term: null };
  }
  const own = HELP_TEXT[key];
  if (own && own.desc) return { title: own.title || '', desc: own.desc, term: own.term || null };
  const t = tourTextFor(key, page);
  if (t && t.desc) return t;
  return null;
}

/** 앵커 키 → 스포트라이트 선택자 (data-help·data-tour 둘 다). */
export const helpSelector = (key) => `[data-help="${key}"],[data-tour="${key}"]`;

/**
 * '이 화면에서 할 일' 안내 스텝 — 첫 장은 화면 소개, 이어서 할 일 1~3개를 스포트라이트.
 * 문구가 없는 화면이면 null(→ 기존 화면 투어로 대신한다).
 */
export function buildTodoSteps(page) {
  const ph = PAGE_HELP[page];
  if (!ph || !ph.what) return null;
  const todo = Array.isArray(ph.todo) ? ph.todo : [];
  const list = todo.map((t, i) => `${i + 1}. ${t.title}`).join('\n');
  const head = {
    el: null,
    title: `📍 ${PAGE_META[page]?.label || '이 화면'}에서 할 일`,
    desc: ph.what,
    sub: list || null,
  };
  const steps = todo.map((t, i) => ({
    el: t.el ? helpSelector(t.el) : null,
    title: `${i + 1}. ${t.title}`,
    desc: t.desc,
    term: t.term || null,
  }));
  return [head, ...steps];
}
