// 한글 오타 교정표 — "정확히 일치하는 문자열"만(추측 금지 원칙 동일).
// 0720 사용성 테스트에서 실제 관찰된 생성 오타.
const KO_TYPO_WORDS = [
  ['도표조지자', '도표 조직자'],
  ['차례를 넘어 응답', '차례를 지켜 응답'],
];

// 숫자 뒤에 공백을 두고 오는 한국어 단위. "3 회" → "3회"
const UNITS = '회|번|개|명|분|초|시간|일|주|주일|개월|달|년|학년|교시|점|퍼센트|％|%';

export function normalizeAIText(text) {
  if (!text || typeof text !== 'string') return text || '';
  let s = text;

  // 1) 한자 → 한글 (확인된 단어만)
  for (const [h, k] of HANJA_WORDS) {
    if (s.includes(h)) s = s.split(h).join(k);
  }

  // 1-1) 한글 오타 → 교정 (확인된 문자열만)
  for (const [t, k] of KO_TYPO_WORDS) {
    if (s.includes(t)) s = s.split(t).join(k);
  }

  // 2) 숫자와 한국어 단위 사이의 공백 제거. 단위 뒤가 한글/공백/문장부호일 때만
  //    바꿔 "3 개월차" 같은 표현도 안전하게 처리한다.
  s = s.replace(new RegExp(`(\\d)\\s+(${UNITS})(?![A-Za-z0-9])`, 'g'), '$1$2');

  // 3) 괄호·따옴표 앞뒤의 불필요한 공백 정리 (표기 흔들림)
  s = s.replace(/\(\s+/g, '(').replace(/\s+\)/g, ')');

  return s;
}

// 치환표에 없는 한자(중국어 혼입 의심)가 남아 있는지 검출 — P11 린트.
// 자동으로 바꾸지 않고(추측 금지) 호출부에서 교사에게 경고만 띄운다.
// 반환: 발견된 한자 연속 구간 배열(중복 제거, 최대 10개). 없으면 [].
export function findHanja(text) {
  if (!text || typeof text !== 'string') return [];
  const m = text.match(/[㐀-䶿一-鿿豈-﫿]+/g);
  return m ? [...new Set(m)].slice(0, 10) : [];
}

