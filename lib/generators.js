// AI 텍스트 생성기 — 엔진 + 도구 카탈로그.
// 설계 근거: GetGPT Studio 역설계(GetGPT_텍스트생성_접목설계.md).
//   도구(Tool) = { 입력 필드(타입) + {{변수}} 프롬프트 템플릿 + 출력형식 }.
//   GetGPT와의 차별점: 사용자 입력값뿐 아니라 "학생 컨텍스트"를 자동 주입한다.
//
// 이 파일은 순수 함수/데이터만 담는다(React 의존 없음). UI는 GeneratorPage.jsx.

import { qabfScores, QABF_SHORT_LABELS } from './qabf';

// ---------------------------------------------------------------------------
// 1) 템플릿 치환 — 프롬프트 본문의 {{변수}}를 값으로 채운다.
//    GetGPT의 @변수 방식과 동일한 개념. 한글 키 안정성을 위해 {{ }} 토큰 사용.
// ---------------------------------------------------------------------------
export function fillTemplate(tpl, vars = {}) {
  return String(tpl || '').replace(/\{\{\s*([^}]+?)\s*\}\}/g, (_, key) => {
    const v = vars[String(key).trim()];
    return v == null ? '' : String(v);
  });
}

// ---------------------------------------------------------------------------
// 2) HWP/NEIS 안전 텍스트 정리 — GetGPT 워터마크 제거기 차용.
//    LLM이 남기는 보이지 않는 유니코드(제로폭·NNBSP 등)와 스마트 문장부호를
//    한글 문서에 그대로 붙여넣어도 깨지지 않도록 정규화한다.
// ---------------------------------------------------------------------------
export function cleanText(s) {
  if (!s) return '';
  return String(s)
    .replace(/[​‌‍⁠﻿]/g, '')   // 제로폭 문자 제거
    .replace(/[      ]/g, ' ') // 비분리/특수 공백 → 일반 공백
    .replace(/[‘’‛]/g, "'")              // 스마트 작은따옴표 → '
    .replace(/[“”]/g, '"')                    // 스마트 큰따옴표 → "
    .replace(/[–—]/g, '-')                    // en/em 대시 → 하이픈
    .replace(/[ \t]+\n/g, '\n')                         // 줄 끝 공백 제거
    .replace(/\n{3,}/g, '\n\n');                        // 과도한 빈 줄 정리
}

// 모델 출력에서 "- "/"• " 목록만 추려 배열로(평어 등 목록형 도구용).
export function parseLines(text) {
  if (!text) return [];
  return String(text)
    .split('\n')
    .map((l) => l.replace(/^\s*\d+[.)]\s*/, '').replace(/^\s*[-•·*]\s*/, '').trim())
    .filter((l) => l.length > 1 && !/^(결과|출력|예시|목록)\s*[:：]?$/.test(l));
}

// ---------------------------------------------------------------------------
// 3) 학생 컨텍스트 빌더 — curStu(학생 레코드) + curStuData(누적 기록)에서
//    비식별 컨텍스트 변수를 만든다. 값이 없으면 키를 만들지 않는다.
//    개인정보 원칙: 학생코드 외 식별정보는 절대 포함하지 않는다.
// ---------------------------------------------------------------------------
export function buildStudentContext(stu, data) {
  const ctx = {};
  if (!stu) return ctx;
  const put = (k, v) => { if (v != null && String(v).trim() !== '') ctx[k] = String(v).trim(); };

  put('학생코드', stu.code || stu.student_code);
  put('기능수준', stu.level);
  put('장애유형', stu.disability);
  put('학생노트', stu.note);

  if (data) {
    // QABF 추정 주요기능 + 심각도
    const resp = data.qabf;
    if (Array.isArray(resp) && resp.some((v) => v >= 0)) {
      const { func, sev } = qabfScores(resp);
      let top = 0;
      for (let i = 1; i < 5; i += 1) if (sev[i] > sev[top]) top = i;
      if (sev[top] > 0) {
        put('QABF주요기능', QABF_SHORT_LABELS[top]);
        put('QABF심각도', `${sev[top]}/15`);
        put('QABF요약', QABF_SHORT_LABELS.map((l, i) => `${l}(기능 ${func[i]}/5·심각도 ${sev[i]}/15)`).join(', '));
      }
    }
    // ABC 관찰 — 최근 3건 요약
    const abc = data.abc;
    if (Array.isArray(abc) && abc.length) {
      const line = abc.slice(-3).map((r) => {
        const a = r.antecedent ?? r.a ?? '-';
        const b = r.behavior ?? r.b ?? '-';
        const c = r.consequence ?? r.c ?? '-';
        return `선행:${a} → 행동:${b} → 결과:${c}`;
      }).join(' / ');
      put('ABC요약', line);
    }
    // BIP 대체행동
    const bip = data.bip;
    if (bip && (bip.alt || bip.fct)) put('대체행동', bip.alt || bip.fct);
  }
  return ctx;
}

// 컨텍스트 객체를 사람이 읽는 한 줄 요약으로(커스텀 도구·전송 미리보기용).
export function summarizeContext(ctx) {
  const order = ['학생코드', '장애유형', '기능수준', 'QABF주요기능', 'QABF심각도', 'ABC요약', '대체행동', '학생노트'];
  return order.filter((k) => ctx[k]).map((k) => `${k}: ${ctx[k]}`).join('\n');
}

// ---------------------------------------------------------------------------
// 4) 최종 프롬프트 합성 — 도구 템플릿 + (폼 값 ∪ 학생 컨텍스트).
//    multiselect 값(배열)은 ", "로 join. '학생맥락' 특수변수는 컨텍스트 요약.
// ---------------------------------------------------------------------------
export function renderPrompt(tool, formValues = {}, ctx = {}) {
  const vars = {};
  Object.entries(formValues).forEach(([k, v]) => {
    vars[k] = Array.isArray(v) ? v.join(', ') : (v ?? '');
  });
  Object.entries(ctx).forEach(([k, v]) => { if (vars[k] == null || vars[k] === '') vars[k] = v; });
  vars['학생맥락'] = summarizeContext(ctx) || '(학생 미선택)';
  return fillTemplate(tool.template, vars);
}

