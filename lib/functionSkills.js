// QABF 응답 → 최상위 기능의 핵심기술 추천. { qabfLabel, func, skills } | null.
// 신체(pain) 기능이 최상위면 { qabfLabel:'신체', func:null, skills:[] } — 호출부가 의료 안내 표시.
export function skillsForQabf(responses) {
  if (!Array.isArray(responses) || !responses.some((v) => v >= 0)) return null;
  const { sev } = qabfScores(responses);
  let top = 0;
  for (let i = 1; i < 5; i += 1) if (sev[i] > sev[top]) top = i;
  if (sev[top] <= 0) return null;
  const qabfLabel = QABF_SHORT_LABELS[top];
  const func = qabfLabelToFunc(qabfLabel) ?? null;
  return { qabfLabel, func, skills: func ? FUNCTION_SKILLS[func] || [] : [] };
}

// AI 프롬프트 주입 블록 — BIP·IEP(행동·사회성 목표) 교육방법 생성 시
// "기능에 맞는 가르칠 기술"과 PBS 3전략(선행·교수·후속결과) 예시를 근거로 제공.
export function functionSkillsBlock(qabfLabel) {
  const func = qabfLabelToFunc(qabfLabel);
  if (!func) return '';
  const skills = FUNCTION_SKILLS[func] || [];
  if (!skills.length) return '';
  const lines = skills.map((s) => {
    const st = s.strategies;
    const parts = [`· ${s.name} — ${s.goal}`];
    if (st) {
      if (st.prev?.length) parts.push(`    선행(예방): ${st.prev.join(' / ')}`);
      if (st.teach?.length) parts.push(`    교수(지도): ${st.teach.join(' / ')}`);
      if (st.conseq?.length) parts.push(`    후속결과(강화): ${st.conseq.join(' / ')}`);
    }
    return parts.join('\n');
  });
  return (
    `[기능 기반 핵심기술 후보] (추정 기능 '${qabfLabel}' → 가르칠 대체 핵심기술 — 기능기반 IEPBS 자료 기준)\n` +
    lines.join('\n') + '\n' +
    `  → 행동·사회성 내용을 다룰 때 이 핵심기술 중 학생에게 맞는 것을 목표·대체행동·교수 내용의 후보로 우선 고려하고, ` +
    `교육방법의 전략은 위 선행·교수·후속결과 예시를 이 학생의 활동·자료에 맞게 구체화해 쓸 것(문장 그대로 복사 금지).\n`
  );
}
