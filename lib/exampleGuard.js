// 형식 본보기의 문장도 코퍼스에 넣는다 — 본보기를 베껴도 잡아낸다.
// 구조 라벨(지도전략: 등)은 요구되는 형식이므로 코퍼스에서 제거.
function sentencesOf(obj) {
  const out = [];
  const walk = (v) => {
    if (v == null) return;
    if (typeof v === 'string') out.push(...v.split(/\r?\n/));
    else if (Array.isArray(v)) v.forEach(walk);
    else if (typeof v === 'object') Object.values(v).forEach(walk);
  };
  walk(obj);
  return out
    .map((s) => s.replace(/^\s*[-•·]\s*/, '').replace(/^(지도전략|지원수준\(촉구·용암\)|강화 스케줄)\s*:\s*/, '').trim())
    .filter((s) => s.length >= 8);
}
const EX_CORPUS = [...PROF_SENTENCES, ...sentencesOf(FORMAT_EX_MATH_OBJ), ...sentencesOf(FORMAT_EX_MOTOR_OBJ), ...sentencesOf(FORMAT_EX_COMM_OBJ)];

const normalize = (s) => String(s == null ? '' : s).replace(/[^0-9A-Za-z가-힣]/g, '');
const WIN = 10; // 정규화 기준 10자(≈한 어절 두세 개) 이상 그대로 겹치면 베끼기로 판정

function collectText(v, out = []) {
  if (v == null) return out;
  if (typeof v === 'string') out.push(v);
  else if (Array.isArray(v)) v.forEach((x) => collectText(x, out));
  else if (typeof v === 'object') Object.values(v).forEach((x) => collectText(x, out));
  return out;
}

/**
 * 생성 결과(문자열/객체)에서 예시 자료 문장과 그대로 겹치는 구절을 찾는다.
 * @returns {string[]} 겹친 원문 조각(중복 제거, 최대 12개). 없으면 [].
 */
export function findExampleEchoes(value) {
  const hay = normalize(collectText(value).join(' '));
  if (!hay) return [];
  const hits = [];
  const seen = new Set();
  for (const src of EX_CORPUS) {
    let lastHit = -10;
    for (let i = 0; i < src.length; i += 2) {
      let j = i;
      let buf = '';
      while (j < src.length && buf.length < WIN) {
        if (/[0-9A-Za-z가-힣]/.test(src[j])) buf += src[j];
        j += 1;
      }
      if (buf.length < WIN || seen.has(buf)) continue;
      if (hay.includes(buf)) {
        seen.add(buf);
        if (i - lastHit >= WIN) hits.push(src.slice(i, j).trim()); // 같은 문장의 이웃 창은 대표 1개만
        lastHit = i;
      }
    }
  }
  return [...new Set(hits)].slice(0, 12);
}
