/** id로 용어 1건 찾기 (없으면 null). */
export function glossaryById(id) {
  return GLOSSARY.find((g) => g.id === id) || null;
}

/** 검색 — 용어명·별칭·풀이에서 부분 일치. 빈 검색어면 전체. */
export function searchGlossary(q) {
  const needle = String(q || '').trim().toLowerCase();
  if (!needle) return GLOSSARY;
  return GLOSSARY.filter((g) =>
    [g.term, g.short, g.more, ...(g.aka || [])].join(' ').toLowerCase().includes(needle)
  );
}
