/** 해당 페이지의 투어 (없으면 null). */
export function getTour(key) {
  return TOURS[key] || null;
}

/**
 * 페이지 키 → 실제로 보여줄 투어 키.
 * 그 페이지 투어가 없으면 소속 영역의 대시보드 투어로, 그것도 없으면 홈 투어로.
 */
export function resolveTourKey(activePage) {
  if (TOURS[activePage]) return activePage;
  const sec = PAGE_SECTION[activePage];
  if (sec && SECTIONS[sec] && TOURS[SECTIONS[sec].dash]) return SECTIONS[sec].dash;
  return 'home';
}
