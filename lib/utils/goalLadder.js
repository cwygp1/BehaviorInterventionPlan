const H = (c) => c >= 0xac00 && c <= 0xd7a3;
const jong = (c) => (c - 0xac00) % 28; // 받침 인덱스(4=ㄴ, 8=ㄹ)
// ㄹ 관형형("정당화할·만들·읽을·들을") → '는'을 붙일 어간("정당화하·만드·읽·듣").
const IRR_L = { 들을: '듣', 걸을: '걷', 물을: '묻', 깨달을: '깨닫', 실을: '싣', 지을: '짓', 이을: '잇', 그을: '긋', 부을: '붓', 나을: '낫', 저을: '젓', 도울: '돕', 주울: '줍', 구울: '굽', 누울: '눕', 기울: '깁' };
function relStem(v) {
  const key = Object.keys(IRR_L).find((k) => v.endsWith(k));
  if (key) return v.slice(0, -key.length) + IRR_L[key];
  const last = v.charCodeAt(v.length - 1);
  if (!H(last) || jong(last) !== 8) return v;
  const prev = v.length >= 2 ? v.charCodeAt(v.length - 2) : 0;
  if (v.endsWith('을') && H(prev) && jong(prev) !== 0) return v.slice(0, -1); // 읽을 → 읽 (매개모음 '을')
  return v.slice(0, -1) + String.fromCharCode(last - 8); // 할→하, 만들→만드, 쓸→쓰, 셀→세
}

/**
 * 성취기준 문장 → "~하는 활동" 관형구.
 *   "…을 탐색한다." → "…을 탐색하는 활동" / "…을 읽는다" → "…을 읽는 활동" / "…을 구할 수 있다" → "…을 구하는 활동"
 *   "…에 흥미를 가진다" → "…에 흥미를 가지는 활동" / 알 수 없는 꼴 → "… 활동"
 */
export function activityPhrase(text) {
  const t = String(text || '').trim().replace(/\.+\s*$/, '');
  if (!t) return '';
  const m = t.match(/^(.*?)(\S+)\s+수\s+있다$/);
  if (m) return m[1] + relStem(m[2]) + '는 활동';
  if (/있다$/.test(t)) return t.slice(0, -2) + '있는 활동';
  if (/는다$/.test(t)) return t.slice(0, -2) + '는 활동';
  if (/하기$/.test(t)) return t.slice(0, -2) + '하는 활동';
  if (/다$/.test(t) && t.length >= 2) {
    const ch = t.charCodeAt(t.length - 2);
    if (H(ch) && jong(ch) === 4) return t.slice(0, -2) + String.fromCharCode(ch - 4) + '는 활동'; // 탐색한다→탐색하는, 기른다→기르는, 쓴다→쓰는
  }
  return t + ' 활동';
}

const stripSelf = (s) => s.replace(/^스스로\s+/, '');
// 태도형(관심·흥미·태도)이거나 원문에 이미 '활동에'가 있으면 "…활동에 관심을 가지는 활동에 참여"처럼 겹치므로,
// ①은 관형구 대신 "교사와 함께 하는 활동에서 …"(전면 지원)로 쓴다.
const ATTITUDE_OR_ACTIVITY = /(기른다|가진다|갖는다|참여한다|느낀다|지닌다|즐긴다|여긴다|갖춘다|가질 수 있다|기를 수 있다|느낄 수 있다|즐길 수 있다|참여할 수 있다)\.?\s*$|활동에\s/;

/** 성취기준 원문 → [①참여, ②시범·단서, ③익숙한 자료, ④도달(원문), ⑤새로운 자료도 스스로] — 모두 "~할 수 있다." */
export function goalLadder(text) {
  const base = toCanDoText(text);
  if (!base) return ['', '', '', '', ''];
  const body = stripSelf(base);
  return [
    ATTITUDE_OR_ACTIVITY.test(String(text || '').trim()) ? '교사와 함께 하는 활동에서 ' + body : activityPhrase(text) + '에 자신의 방식으로 참여할 수 있다.',
    '교사의 시범과 단서를 받아 ' + body,
    '익숙한 자료·상황에서 ' + body,
    base,
    '새로운 자료·상황에서도 스스로 ' + body,
  ];
}

