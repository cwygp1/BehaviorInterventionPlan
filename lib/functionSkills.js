import { qabfScores, QABF_SHORT_LABELS } from './qabf';

// QABF 라벨 → 문서 기능명. 신체는 null(핵심기술 카탈로그 비대상).
// 라벨 표기가 소스마다 달라('자동·감각'/'자동감각') 조회 시 구분점·공백을 제거해 정규화한다.
const QABF_TO_FUNC_NORM = { '관심': '관심', '회피': '회피', '자동감각': '감각추구', '신체': null, '강화물': '획득' };
export const qabfLabelToFunc = (label) => {
  const key = String(label || '').replace(/[·\s]/g, '');
  return key in QABF_TO_FUNC_NORM ? QABF_TO_FUNC_NORM[key] : undefined;
};

